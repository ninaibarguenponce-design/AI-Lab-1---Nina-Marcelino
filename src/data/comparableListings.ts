export function getCompsForProperty(
  neighborhoodId: string,
  bedrooms?: number
): {
  comps: ComparableListing[];
  medianPrice: number;
  minPrice: number;
  maxPrice: number;
  avgOccupancy: number;
  totalFound: number;
} {
  // First attempt: exact neighborhood match
  let matches = DC_COMPARABLE_LISTINGS.filter(
    (item) => item.neighborhoodId === neighborhoodId
  );

  // If we have bedroom filter and enough matches, prefer matching bedrooms
  if (bedrooms !== undefined) {
    const exactBedMatches = matches.filter((item) => item.bedrooms === bedrooms);
    if (exactBedMatches.length > 0) {
      matches = exactBedMatches;
    }
  }

  // Fallback: If few matches in this neighborhood, include adjacent listings
  if (matches.length === 0) {
    matches = DC_COMPARABLE_LISTINGS.slice(0, 4);
  }

  const prices = matches.map((m) => m.nightlyPrice).sort((a, b) => a - b);
  const minPrice = prices[0] || 150;
  const maxPrice = prices[prices.length - 1] || 350;
  const medianPrice = prices[Math.floor(prices.length / 2)] || 220;
  const avgOccupancy = Math.round(
    matches.reduce((acc, curr) => acc + curr.estimatedOccupancy, 0) / matches.length
  );

  return {
    comps: matches,
    medianPrice,
    minPrice,
    maxPrice,
    avgOccupancy,
    totalFound: matches.length,
  };
}
